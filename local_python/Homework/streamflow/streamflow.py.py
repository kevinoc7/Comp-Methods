import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

L = 6      # ft
RA = 170   # lb
RB = 410   # lb
P1 = 100   # lb
q1 = 120   # lb/ft
q2 = 120   # lb/ft

x = np.linspace(0, L, 500)

V = np.zeros_like(x)

for i in range(len(x)):
    if x[i] < 2:
        V[i] = RA - q1 * x[i]

    elif x[i] < 4:
        V[i] = RA - (q1 * 2) - P1

    else:
        V[i] = RA - (q1 * 2) - P1 + RB - q2 * (x[i] - 4)

plt.figure(figsize=(10,6))
plt.plot(x, V, linewidth=2)

plt.fill_between(x, V, 0, alpha=0.3)

plt.axhline(0, color='black')

plt.title('Shear Diagram')
plt.xlabel('x (ft)')
plt.ylabel('V (lb)')
plt.grid(True)

plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

L = 6      # ft
RA = 170   # lb
RB = 410   # lb
P1 = 100   # lb
q1 = 120   # lb/ft
q2 = 120   # lb/ft

x = np.linspace(0, L, 500)

M = np.zeros_like(x)

for i in range(len(x)):
    if x[i] < 2:
        M[i] = (RA * x[i]) - (q1 * x[i]**2 / 2)

    elif x[i] < 4:
        M[i] = (RA * x[i]) \
               - (q1 * 2 * (x[i] - 1)) \
               - (P1 * (x[i] - 2))

    else:
        M[i] = (RA * x[i]) \
               - (q1 * 2 * (x[i] - 1)) \
               - (P1 * (x[i] - 2)) \
               + (RB * (x[i] - 4)) \
               - (q2 * (x[i] - 4) * ((x[i] - 4) / 2))

plt.figure(figsize=(10,6))
plt.plot(x, M, linewidth=2, color='red')

plt.fill_between(x, M, 0, color='red', alpha=0.3)

plt.axhline(0, color='black')

plt.title('Moment Diagram')
plt.xlabel('x (ft)')
plt.ylabel('M (lb-ft)')
plt.grid(True)

plt.show()

